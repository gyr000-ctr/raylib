const char *GetFileExtension(const char *fileName)
{
    const char *dot = strrchr(fileName, '.');
    return (dot != NULL)? dot : "";
}

bool IsFileExtension(const char *fileName, const char *ext)
{
    const char *fileExt = GetFileExtension(fileName);
    if (fileExt == NULL) return false;

    // ext may be a semicolon-separated list (".wav;.ogg")
    bool result = false;
    char exts[128];
    strncpy(exts, ext, sizeof(exts) - 1);
    exts[sizeof(exts) - 1] = '\0';

    char *token = strtok(exts, ";");
    while (token != NULL)
    {
        if (strcasecmp(fileExt, token) == 0) { result = true; break; }
        token = strtok(NULL, ";");
    }

    return result;
}

const char *GetFileName(const char *filePath)
{
    const char *name = strrchr(filePath, '/');
    return (name != NULL)? name + 1 : filePath;
}

const char *GetFileNameWithoutExt(const char *filePath)
{
    static char name[256];
    const char *fileName = GetFileName(filePath);
    const char *dot = strrchr(fileName, '.');
    size_t len = (dot != NULL)? (size_t)(dot - fileName) : strlen(fileName);
    if (len >= sizeof(name)) len = sizeof(name) - 1;
    memcpy(name, fileName, len);
    name[len] = '\0';
    return name;
}

