int main(void)
{
    InitTestAudioSystem();

    TestWavSmplParsing();
    TestWavLoopStreaming();
    TestWavFullLoopUnchanged();
    TestManualLoopPoints();
    TestInvalidLoopPoints();
    TestSeekWithLoopPoints();
    TestOggLoopPoints();
    TestUnsupportedFormats();
    TestPauseResume();
    TestMp3LoopPoints();

    printf("\n%d checks run, %d failed\n", testsRun, testsFailed);
    if (testsFailed == 0) printf("ALL TESTS PASSED\n");

    return (testsFailed == 0)? 0 : 1;
}
