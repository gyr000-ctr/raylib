// Test 7: Ogg LOOPSTART/LOOPLENGTH comments (file + memory) and seamless looping
//----------------------------------------------------------------------------------
// Verify one OGG sub-buffer against the ground truth (s16 interleaved)
static void VerifySubBufferOgg(Music *music, int subBuffer, SeqModel *model, const short *groundTruth, const char *tag)
{
    int channels = music->stream.channels;
    short *data = (short *)music->stream.buffer->data + subBuffer*SUBBUFFER_FRAMES*channels;

    for (int f = 0; f < SUBBUFFER_FRAMES; f++)
    {
        unsigned int frame = ModelNext(model);
        for (int c = 0; c < channels; c++)
        {
            if (data[f*channels + c] != groundTruth[frame*channels + c])
            {
                CHECK_MSG(false, "%s: sub-buffer %d frame %d ch %d: got %d, expected frame %u sample %d",
                          tag, subBuffer, f, c, data[f*channels + c], frame, groundTruth[frame*channels + c]);
                return;
            }
        }
    }

    testsRun++;
}

static void TestOggLoopPoints(void)
{
    printf("TEST: Ogg Vorbis comment loop points\n");

    Music music = LoadMusicStream("tests/resources/loop_tags.ogg");
    CHECK_MSG(IsMusicValid(music), "loop_tags.ogg should load");

    unsigned int loopStart = 0, loopEnd = 0;
    bool enabled = GetMusicLoopPoints(music, &loopStart, &loopEnd);
    CHECK_MSG(enabled, "LOOPSTART/LOOPLENGTH comments should enable loop points");
    CHECK_MSG(loopStart == 1000, "ogg loop start should be 1000, got %u", loopStart);
    CHECK_MSG(loopEnd == 4000, "ogg loop end should be 4000, got %u", loopEnd);

    // Same through the memory loader
    int dataSize = 0;
    unsigned char *fileData = LoadFileData("tests/resources/loop_tags.ogg", &dataSize);
    Music memMusic = LoadMusicStreamFromMemory(".ogg", fileData, dataSize);
    loopStart = loopEnd = 0;
    enabled = GetMusicLoopPoints(memMusic, &loopStart, &loopEnd);
    CHECK_MSG(enabled && (loopStart == 1000) && (loopEnd == 4000),
              "memory-loaded ogg loop points should be [1000, 4000), got [%u, %u)", loopStart, loopEnd);
    UnloadMusicStream(memMusic);
    UnloadFileData(fileData);

    // Ground truth: decode the whole file once with stb_vorbis directly
    stb_vorbis *vorbis = stb_vorbis_open_filename("tests/resources/loop_tags.ogg", NULL, NULL);
    CHECK_MSG(vorbis != NULL, "loop_tags.ogg should open with stb_vorbis");
    stb_vorbis_info info = stb_vorbis_get_info(vorbis);
    unsigned int totalFrames = stb_vorbis_stream_length_in_samples(vorbis);
    short *groundTruth = (short *)malloc(totalFrames*info.channels*sizeof(short));
    unsigned int decoded = 0;
    while (decoded < totalFrames)
    {
        int read = stb_vorbis_get_samples_short_interleaved(vorbis, info.channels,
            groundTruth + decoded*info.channels, (totalFrames - decoded)*info.channels);
        if (read <= 0) break;
        decoded += read;
    }
    stb_vorbis_close(vorbis);
    CHECK_MSG(decoded == totalFrames, "ground truth decode should produce %u frames, got %u", totalFrames, decoded);

    // Stream and verify every frame against the ground truth through the loop
    PlayMusicStream(music);
    SeqModel model = ModelInit(totalFrames, 1000, 4000);
    int channels = music.stream.channels;

    UpdateMusicStream(music);   // Fills both sub-buffers
    VerifySubBufferOgg(&music, 0, &model, groundTruth, "ogg");
    VerifySubBufferOgg(&music, 1, &model, groundTruth, "ogg");

    for (int i = 0; i < 8; i++)
    {
        int sub = i%2;
        music.stream.buffer->isSubBufferProcessed[sub] = true;
        UpdateMusicStream(music);
        VerifySubBufferOgg(&music, sub, &model, groundTruth, "ogg");
    }

    // Seek inside the loop region, then keep streaming through the loop
    SeekMusicStream(music, 0.1f);       // ~frame 2205 of 22050 Hz
    unsigned int seekPos = music.stream.buffer->framesProcessed;
    CHECK_MSG((seekPos >= 1000) && (seekPos < 4000),
              "ogg seek should land inside loop region [1000, 4000), got %u", seekPos);

    model.pos = seekPos;
    UpdateMusicStream(music);           // Seek marks both sub-buffers for refill
    VerifySubBufferOgg(&music, 0, &model, groundTruth, "ogg-post-seek");
    VerifySubBufferOgg(&music, 1, &model, groundTruth, "ogg-post-seek");

    for (int i = 0; i < 4; i++)
    {
        int sub = i%2;
        music.stream.buffer->isSubBufferProcessed[sub] = true;
        UpdateMusicStream(music);
        VerifySubBufferOgg(&music, sub, &model, groundTruth, "ogg-post-seek");
    }

    free(groundTruth);
    UnloadMusicStream(music);
}

//----------------------------------------------------------------------------------
// Test 10: MP3 manual loop points, sample-exact through the loop
//----------------------------------------------------------------------------------
static void TestMp3LoopPoints(void)
{
    printf("TEST: MP3 loop points (sample-exact)\n");

    Music music = LoadMusicStream("examples/audio/resources/country.mp3");
    CHECK_MSG(IsMusicValid(music), "country.mp3 should load");

    SetMusicLoopPoints(music, 5000, 9000);
    unsigned int loopStart = 0, loopEnd = 0;
    CHECK_MSG(GetMusicLoopPoints(music, &loopStart, &loopEnd) && (loopStart == 5000) && (loopEnd == 9000),
              "mp3 loop points should be [5000, 9000), got [%u, %u)", loopStart, loopEnd);

    // Ground truth: decode the whole file once with drmp3 directly
    drmp3 mp3;
    CHECK_MSG(drmp3_init_file(&mp3, "examples/audio/resources/country.mp3", NULL), "country.mp3 should open with drmp3");
    drmp3_uint64 totalFrames = drmp3_get_pcm_frame_count(&mp3);
    int channels = music.stream.channels;
    float *groundTruth = (float *)malloc(totalFrames*channels*sizeof(float));
    drmp3_uint64 decoded = drmp3_read_pcm_frames_f32(&mp3, totalFrames, groundTruth);
    drmp3_uninit(&mp3);
    CHECK_MSG(decoded == totalFrames, "mp3 ground truth decode should produce %llu frames, got %llu",
              (unsigned long long)totalFrames, (unsigned long long)decoded);

    PlayMusicStream(music);
    SeqModel model = ModelInit((unsigned int)totalFrames, 5000, 9000);

    // MP3 streams decode to 32-bit float
    for (int i = 0; i < 10; i++)
    {
        int sub = i%2;
        music.stream.buffer->isSubBufferProcessed[sub] = true;
        UpdateMusicStream(music);
        float *data = (float *)music.stream.buffer->data + sub*SUBBUFFER_FRAMES*channels;
        bool ok = true;
        for (int f = 0; f < SUBBUFFER_FRAMES && ok; f++)
        {
            unsigned int frame = ModelNext(&model);
            for (int c = 0; c < channels; c++)
            {
                if (data[f*channels + c] != groundTruth[frame*channels + c])
                {
                    CHECK_MSG(false, "mp3: refill %d frame %d ch %d: got %f, expected frame %u sample %f",
                              i, f, c, data[f*channels + c], frame, groundTruth[frame*channels + c]);
                    ok = false;
                    break;
                }
            }
        }
        if (ok) testsRun++;
    }

    free(groundTruth);
    UnloadMusicStream(music);
}

