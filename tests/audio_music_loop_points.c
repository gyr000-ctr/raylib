static int testsRun = 0;
static int testsFailed = 0;

#define CHECK_MSG(cond, ...) do { \
        testsRun++; \
        if (!(cond)) { \
            testsFailed++; \
            printf("FAIL [line %d]: ", __LINE__); \
            printf(__VA_ARGS__); \
            printf("\n"); \
        } \
    } while (0)

#define SUBBUFFER_FRAMES 4096       // Must match SetAudioStreamBufferSizeDefault()

// Deterministic, single-threaded audio system init (no real device needed)
static void InitTestAudioSystem(void)
{
    ma_mutex_init(&AUDIO.System.lock);
    AUDIO.System.device.sampleRate = 48000;
    AUDIO.System.device.playback.format = ma_format_f32;
    AUDIO.System.device.playback.channels = 2;
    AUDIO.System.device.playback.internalPeriodSizeInFrames = 512;
    AUDIO.System.isReady = true;

    SetAudioStreamBufferSizeDefault(SUBBUFFER_FRAMES);
}

// Model of the expected source-frame sequence produced by the music streamer
typedef struct SeqModel {
    unsigned int pos;           // Current source frame expected next
    unsigned int frameCount;    // Total frames in the source
    unsigned int loopStart;     // Active loop start (frameCount if no custom loop points)
    unsigned int loopEnd;       // Active loop end (exclusive)
} SeqModel;

static SeqModel ModelInit(unsigned int frameCount, unsigned int loopStart, unsigned int loopEnd)
{
    SeqModel model = { 0 };
    model.pos = 0;
    model.frameCount = frameCount;
    model.loopStart = loopStart;
    model.loopEnd = loopEnd;
    return model;
}

static unsigned int ModelNext(SeqModel *model)
{
    unsigned int frame = model->pos++;
    if (model->pos == model->loopEnd) model->pos = model->loopStart;
    return frame;
}

// Verify the contents of one sub-buffer against the model (mono s16 index-encoded WAV)
static void VerifySubBufferWav(Music *music, int subBuffer, SeqModel *model, const char *tag)
{
    short *data = (short *)music->stream.buffer->data + subBuffer*SUBBUFFER_FRAMES;

    for (int f = 0; f < SUBBUFFER_FRAMES; f++)
    {
        unsigned int expected = ModelNext(model);
        if (data[f] != (short)expected)
        {
            CHECK_MSG(false, "%s: sub-buffer %d frame %d: got sample %d, expected frame %u",
                      tag, subBuffer, f, data[f], expected);
            return;
        }
    }

    testsRun++;     // One check per sub-buffer is enough on success
}

// Simulate the device consuming one sub-buffer, then refill and verify it
static void ConsumeAndVerifyWav(Music *music, int subBuffer, SeqModel *model, const char *tag)
{
    music->stream.buffer->isSubBufferProcessed[subBuffer] = true;
    UpdateMusicStream(*music);
    VerifySubBufferWav(music, subBuffer, model, tag);
}

// Initial refill: both sub-buffers are marked processed after load/play
static void RefillAllAndVerifyWav(Music *music, SeqModel *model, const char *tag)
{
    UpdateMusicStream(*music);
    VerifySubBufferWav(music, 0, model, tag);
    VerifySubBufferWav(music, 1, model, tag);
}

//----------------------------------------------------------------------------------
// Test 1: WAV smpl chunk loop points are parsed on load (file + memory)
//----------------------------------------------------------------------------------
static void TestWavSmplParsing(void)
{
    printf("TEST: WAV smpl chunk parsing\n");

    Music music = LoadMusicStream("tests/resources/loop_smpl.wav");
    CHECK_MSG(IsMusicValid(music), "loop_smpl.wav should load");

    unsigned int loopStart = 0, loopEnd = 0;
    bool enabled = GetMusicLoopPoints(music, &loopStart, &loopEnd);
    CHECK_MSG(enabled, "smpl loop points should be enabled after load");
    CHECK_MSG(loopStart == 2000, "loop start should be 2000, got %u", loopStart);
    CHECK_MSG(loopEnd == 5000, "loop end should be 5000 (exclusive), got %u", loopEnd);
    UnloadMusicStream(music);

    // Same through the memory loader
    int dataSize = 0;
    unsigned char *fileData = LoadFileData("tests/resources/loop_smpl.wav", &dataSize);
    CHECK_MSG(fileData != NULL, "loop_smpl.wav should be readable");

    Music memMusic = LoadMusicStreamFromMemory(".wav", fileData, dataSize);
    CHECK_MSG(IsMusicValid(memMusic), "loop_smpl.wav should load from memory");

    loopStart = loopEnd = 0;
    enabled = GetMusicLoopPoints(memMusic, &loopStart, &loopEnd);
    CHECK_MSG(enabled, "smpl loop points should be enabled after memory load");
    CHECK_MSG(loopStart == 2000 && loopEnd == 5000,
              "memory-loaded loop points should be [2000, 5000), got [%u, %u)", loopStart, loopEnd);

    UnloadMusicStream(memMusic);
    UnloadFileData(fileData);

    // A WAV without a smpl chunk must not enable loop points
    Music plain = LoadMusicStream("tests/resources/plain.wav");
    CHECK_MSG(IsMusicValid(plain), "plain.wav should load");
    enabled = GetMusicLoopPoints(plain, &loopStart, &loopEnd);
    CHECK_MSG(!enabled, "plain.wav should not have loop points");
    CHECK_MSG(loopStart == 0 && loopEnd == plain.frameCount,
              "disabled loop points should report the full range, got [%u, %u)", loopStart, loopEnd);
    UnloadMusicStream(plain);
}

//----------------------------------------------------------------------------------
// Test 2: WAV streaming wraps seamlessly at the loop end (sample-exact)
//----------------------------------------------------------------------------------
static void TestWavLoopStreaming(void)
{
    printf("TEST: WAV loop streaming (sample-exact)\n");

    Music music = LoadMusicStream("tests/resources/loop_smpl.wav");
    CHECK_MSG(IsMusicValid(music), "loop_smpl.wav should load");
    PlayMusicStream(music);

    // Loop is [2000, 5000): 3000 frames < 4096-frame sub-buffer,
    // so sub-buffers regularly contain multiple loop wraps
    SeqModel model = ModelInit(music.frameCount, 2000, 5000);

    RefillAllAndVerifyWav(&music, &model, "wav-loop");
    for (int i = 0; i < 12; i++) ConsumeAndVerifyWav(&music, i%2, &model, "wav-loop");

    CHECK_MSG(music.stream.buffer->streamPosition == model.pos,
              "decoder position %u should match model %u",
              music.stream.buffer->streamPosition, model.pos);

    UnloadMusicStream(music);
}

