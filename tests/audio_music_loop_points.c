/*******************************************************************************************
*
*   audio_music_loop_points.c - Tests for sample-accurate Music loop points
*
*   Verifies:
*     1. WAV smpl chunk loop points are parsed on load (file and memory)
*     2. Ogg Vorbis LOOPSTART/LOOPLENGTH comments are parsed on load
*     3. Streaming wraps seamlessly from loop end to loop start (sample-exact,
*        no dropped/duplicated frames, loop may be smaller than a sub-buffer)
*     4. Full-stream looping is sample-identical when no loop points are set
*     5. Invalid loop points (reversed, zero-length, out-of-bounds) are handled
*     6. Seeking lands inside the loop region and keeps looping correctly
*     7. Formats without loop point support (QOA, XM) reject them gracefully
*     8. Pause/resume does not disturb the stream position
*
*   How it works:
*   The test includes raudio.c directly and drives UpdateMusicStream() manually,
*   simulating the audio device consuming sub-buffers one at a time. The music
*   stream buffer contents are then compared frame-by-frame against an
*   independent model of the expected source-frame sequence.
*
*   Build and run from the repository root:
*     gcc -o tests/audio_music_loop_points tests/audio_music_loop_points.c -Isrc -Isrc/external -lm -lpthread -ldl
*     ./tests/audio_music_loop_points
*
*   Fixtures in tests/resources/ are generated by tests/generate_fixtures.py
*
********************************************************************************************/

