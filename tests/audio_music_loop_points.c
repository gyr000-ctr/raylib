//----------------------------------------------------------------------------------
// Test 4: manual SetMusicLoopPoints, tiny loop, and clearing back to full loop
//----------------------------------------------------------------------------------
static void TestManualLoopPoints(void)
{
    printf("TEST: manual set/clear of loop points\n");

    Music music = LoadMusicStream("tests/resources/plain.wav");
    PlayMusicStream(music);

    // Tiny 100-frame loop: dozens of wraps inside a single 4096-frame sub-buffer
    SetMusicLoopPoints(music, 100, 200);

    unsigned int loopStart = 0, loopEnd = 0;
    CHECK_MSG(GetMusicLoopPoints(music, &loopStart, &loopEnd) && (loopStart == 100) && (loopEnd == 200),
              "loop points should be [100, 200), got [%u, %u)", loopStart, loopEnd);

    SeqModel model = ModelInit(music.frameCount, 100, 200);
    RefillAllAndVerifyWav(&music, &model, "wav-tiny-loop");
    for (int i = 0; i < 4; i++) ConsumeAndVerifyWav(&music, i%2, &model, "wav-tiny-loop");

    // Clearing (loopEnd = 0) restores full-stream looping from the current position
    SetMusicLoopPoints(music, 0, 0);
    CHECK_MSG(!GetMusicLoopPoints(music, &loopStart, &loopEnd), "loop points should be cleared");

    SeqModel fullModel = ModelInit(music.frameCount, 0, music.frameCount);
    fullModel.pos = music.stream.buffer->streamPosition;    // Decoder continues from current position
    for (int i = 0; i < 6; i++) ConsumeAndVerifyWav(&music, i%2, &fullModel, "wav-cleared");

    UnloadMusicStream(music);
}

//----------------------------------------------------------------------------------
// Test 5: invalid loop points (reversed, zero-length, out-of-bounds)
//----------------------------------------------------------------------------------
static void TestInvalidLoopPoints(void)
{
    printf("TEST: invalid loop point handling\n");

    Music music = LoadMusicStream("tests/resources/plain.wav");
    unsigned int loopStart = 0, loopEnd = 0;

    // Zero-length loop: rejected, stays disabled
    SetMusicLoopPoints(music, 500, 500);
    CHECK_MSG(!GetMusicLoopPoints(music, &loopStart, &loopEnd), "zero-length loop should be rejected");

    // Reversed loop: rejected, stays disabled
    SetMusicLoopPoints(music, 6000, 4000);
    CHECK_MSG(!GetMusicLoopPoints(music, &loopStart, &loopEnd), "reversed loop should be rejected");

    // Out-of-bounds loop end: clamped to frame count
    SetMusicLoopPoints(music, 100, 999999);
    CHECK_MSG(GetMusicLoopPoints(music, &loopStart, &loopEnd) && (loopEnd == music.frameCount),
              "out-of-bounds loop end should be clamped to %u, got %u", music.frameCount, loopEnd);

    // Loop covering the whole stream is valid and behaves like full looping
    SetMusicLoopPoints(music, 0, music.frameCount);
    CHECK_MSG(GetMusicLoopPoints(music, &loopStart, &loopEnd) && (loopStart == 0) && (loopEnd == music.frameCount),
              "full-range loop points should be accepted");

    PlayMusicStream(music);
    SeqModel model = ModelInit(music.frameCount, 0, music.frameCount);
    RefillAllAndVerifyWav(&music, &model, "wav-full-range");
    for (int i = 0; i < 6; i++) ConsumeAndVerifyWav(&music, i%2, &model, "wav-full-range");

    UnloadMusicStream(music);
}

//----------------------------------------------------------------------------------
// Test 6: seeking with loop points active
//----------------------------------------------------------------------------------
static void TestSeekWithLoopPoints(void)
{
    printf("TEST: seek with loop points\n");

    Music music = LoadMusicStream("tests/resources/loop_smpl.wav");     // Loop [2000, 5000)
    PlayMusicStream(music);

    // Stream a bit, then seek inside the loop region
    SeqModel model = ModelInit(music.frameCount, 2000, 5000);
    RefillAllAndVerifyWav(&music, &model, "wav-seek-pre");

    SeekMusicStream(music, 0.5f);       // 0.5s * 8000 Hz = frame 4000 exactly
    CHECK_MSG(music.stream.buffer->framesProcessed == 4000,
              "seek to 0.5s should land on frame 4000, got %u", music.stream.buffer->framesProcessed);

    model.pos = 4000;
    RefillAllAndVerifyWav(&music, &model, "wav-seek");
    for (int i = 0; i < 6; i++) ConsumeAndVerifyWav(&music, i%2, &model, "wav-seek");

    // Seeking past the loop end is clamped to the loop region
    SeekMusicStream(music, 1.4f);       // Frame ~11200, past loop end 5000
    CHECK_MSG(music.stream.buffer->framesProcessed == 4999,
              "seek past loop end should clamp to frame 4999, got %u",
              music.stream.buffer->framesProcessed);

    model.pos = 4999;
    RefillAllAndVerifyWav(&music, &model, "wav-seek-clamp");
    for (int i = 0; i < 4; i++) ConsumeAndVerifyWav(&music, i%2, &model, "wav-seek-clamp");

    // Played time must report a position inside the loop region
    float played = GetMusicTimePlayed(music);
    CHECK_MSG((played >= 2000.0f/8000.0f) && (played < 5000.0f/8000.0f),
              "played time %fs should be inside loop region [0.25, 0.625)", played);

    UnloadMusicStream(music);
}

